def main():
    if not os.path.exists(FILE):
        raise SystemExit("先跑 questions.py 生成 问答记录.md")
    text = io.open(FILE, encoding="utf-8").read()
    if "## 人工复核（最终判定以此为准）" in text:
        print("复核段已存在，跳过")
        return
    marker = "\n## 汇总"
    if marker in text:
        head, tail = text.split(marker, 1)
        text = head + REVIEW + marker + tail
    else:
        text += REVIEW
    io.open(FILE, "w", encoding="utf-8").write(text)
    print("已写入人工复核段：", FILE)


if __name__ == "__main__":
    main()
